-- C. List all open lost/found reports
SELECT i.item_id, i.item_name, i.category, i.description,
       i.location, i.item_date, i.report_type, i.status,
       u.full_name AS reported_by
FROM items i
JOIN users u ON u.user_id = i.user_id
WHERE i.status = 'OPEN'
ORDER BY i.created_at DESC;

-- D. Search by item name (example: replace the search term)
SELECT item_id, item_name, category, location, item_date, report_type, status
FROM items
WHERE item_name LIKE '%Bottle%';

-- E. Filter by category and report type
SELECT item_id, item_name, category, location, item_date, report_type, status
FROM items
WHERE category = 'Electronics' AND report_type = 'FOUND';

-- F. List claims with claimant and item details
SELECT c.claim_id, i.item_name, claimant.full_name AS claimant,
       c.claim_description, c.claim_date, c.status
FROM claims c
JOIN items i ON i.item_id = c.item_id
JOIN users claimant ON claimant.user_id = c.claimant_id
ORDER BY c.claim_date DESC;

